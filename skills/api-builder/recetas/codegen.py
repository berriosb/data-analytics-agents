def generate_tests(info: AnalyzeResult, endpoint: str = "predict") -> str:
    func = info.func
    has_params = len(func.params) > 0
    # Construir un payload de ejemplo usando defaults si los hay
    example_payload = {}
    for p in func.params:
        if p.default is not None:
            example_payload[p.name] = p.default
        elif p.annotation in ("int", "float"):
            example_payload[p.name] = 0
        elif p.annotation == "str":
            example_payload[p.name] = "test"
        elif p.annotation == "bool":
            example_payload[p.name] = False
        else:
            example_payload[p.name] = None

    import json
    payload_str = json.dumps(example_payload, indent=8, default=str)
    # json.dumps emite 'true'/'false'/'null' (JS); el test es Python — fix.
    payload_str = payload_str.replace(": true", ": True").replace(": false", ": False").replace(": null", ": None")
    if has_params:
        call_line = f'r = client.post("/{endpoint}", json=payload)'
    else:
        call_line = f'r = client.get("/{endpoint}")'
    return (
        f'"""\nSmoke tests auto-generated for {func.qualified_name}.\n"""\n'
        f'from fastapi.testclient import TestClient\n'
        f'from app import app\n'
        f'\n'
        f'client = TestClient(app)\n'
        f'\n'
        f'\n'
        f'def test_health() -> None:\n'
        f'    r = client.get("/health")\n'
        f'    assert r.status_code == 200\n'
        f'    assert r.json() == {{"status": "ok"}}\n'
        f'\n'
        f'\n'
        f'def test_schema() -> None:\n'
        f'    r = client.get("/schema")\n'
        f'    assert r.status_code == 200\n'
        f'    assert "properties" in r.json()\n'
        f'\n'
        f'\n'
        f'def test_{endpoint}() -> None:\n'
        f'    payload = {payload_str}\n'
        f'    {call_line}\n'
        f'    assert r.status_code == 200, r.text\n'
        f'    # El body exacto depende de la funcion del usuario — no assert sobre keys\n'
        f'    assert r.json() is not None\n'
    )