def generate_pydantic_model(info: AnalyzeResult, model_name: str = "InputModel") -> str:
    """Genera el codigo Python del modelo pydantic a partir de los params."""
    fields = []
    for p in info.func.params:
        ann = p.annotation or "Any"
        if p.required:
            fields.append(f"    {p.name}: {ann}")
        else:
            default = _py_default(p.default)
            fields.append(f"    {p.name}: {ann} = {default}")
    body = "\n".join(fields) if fields else "    pass"
    return (
        f"from pydantic import BaseModel, Field\n"
        f"from typing import Any, Optional\n\n\n"
        f"class {model_name}(BaseModel):\n"
        f"{body}\n"
    )


def _py_default(value: object) -> str:
    """Representacion segura de un default value."""
    if value is None:
        return "None"
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return repr(value)
    # Para defaults raros (objetos custom), None + warning
    return "None  # type: ignore  # default custom"


def generate_fastapi_app(info: AnalyzeResult, pydantic_code: str,
                         endpoint_name: str | None = None,
                         api_key: str | None = None) -> str:
    """Genera el codigo de app.py con FastAPI."""
    ep = endpoint_name or "predict"
    func = info.func
    has_params = len(func.params) > 0

    # Si no hay params, el endpoint es GET; si hay, POST
    method = "GET" if not has_params else "POST"

    # Construir la llamada a la funcion desde el modelo pydantic
    if has_params:
        kwargs = ", ".join(f"{p.name}=payload.{p.name}" for p in func.params)
    else:
        kwargs = ""

    # Auth opcional
    auth_decorator = ""
    auth_import = ""
    if api_key:
        auth_import = "import os\n"
        auth_decorator = (
            "\n\ndef _require_api_key(x_api_key: str = Header(default='')) -> None:\n"
            "    expected = os.environ.get('API_KEY', '')\n"
            "    if expected and x_api_key != expected:\n"
            "        raise HTTPException(status_code=401, detail='Invalid API key')\n"
        )

    # Documentacion del endpoint (del docstring)
    first_line = (func.docstring or f"Run {func.name} and return its result as JSON.").split("\n")[0]

    return (
        f'"""\nAuto-generated by data-analytics-agents · api-builder\n'
        f'Source: {func.module_path}\n'
        f'Function: {func.qualified_name}\n'
        f'Generated at: see git log\n"""\n'
        f'{auth_import}'
        f'from fastapi import FastAPI, HTTPException\n'
        f'from fastapi import Header\n'
        f'from pydantic import BaseModel\n'
        f'from typing import Any\n'
        f'\n'
        f'import importlib.util\n'
        f'from pathlib import Path\n'
        f'\n'
        f'{pydantic_code}'
        f'\n\n'
        f'app = FastAPI(\n'
        f'    title="{func.name} API",\n'
        f'    description="{first_line}",\n'
        f'    version="0.1.0",\n'
        f')\n'
        f'{auth_decorator}'
        f'\n\n'
        f'# Cargar el modulo de analisis una sola vez al startup\n'
        f'_ANALYSIS_PATH = Path(__file__).parent / "analysis.py"\n'
        f'_spec = importlib.util.spec_from_file_location("_analysis", _ANALYSIS_PATH)\n'
        f'_analysis_mod = importlib.util.module_from_spec(_spec)\n'
        f'_spec.loader.exec_module(_analysis_mod)  # noqa: E402\n'
        f'_func = getattr(_analysis_mod, "{func.name}")\n'
        f'\n\n'
        f'@app.get("/health")\n'
        f'def health() -> dict:\n'
        f'    """Health check endpoint."""\n'
        f'    return {{"status": "ok"}}\n'
        f'\n\n'
        f'@app.{method.lower()}("/{ep}")\n'
        f'{"@_require_api_key" if api_key else ""}\n'
        f'def {ep}(payload: InputModel) -> Any:\n'
        f'    """{first_line}"""\n'
        f'    try:\n'
        f'        result = _func({kwargs})\n'
        f'    except Exception as e:\n'
        f'        raise HTTPException(status_code=500, detail=str(e))\n'
        f'    return result\n'
        f'\n\n'
        f'@app.get("/schema")\n'
        f'def schema() -> dict:\n'
        f'    """Devuelve el input schema como JSON."""\n'
        f'    return InputModel.model_json_schema()\n'
    )


def generate_requirements(info: AnalyzeResult) -> str:
    """Genera requirements.txt: fastapi, uvicorn, pydantic + imports del usuario."""
    deps = [
        "fastapi>=0.110",
        "uvicorn[standard]>=0.27",
        "pydantic>=2.0",
    ]
    deps.extend(info.imports)
    return "\n".join(deps) + "\n"


def generate_dockerfile() -> str:
    return (
        "FROM python:3.11-slim\n"
        "\n"
        "WORKDIR /app\n"
        "\n"
        "COPY requirements.txt .\n"
        "RUN pip install --no-cache-dir -r requirements.txt\n"
        "\n"
        "COPY . .\n"
        "\n"
        "EXPOSE 8000\n"
        "\n"
        'CMD ["uvicorn", "app:app", "--host", "0.0.0.0", "--port", "8000"]\n'
    )


